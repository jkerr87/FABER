function FABER_safety_smoketest()
% Small mechanical smoke test; run in MATLAB on your machine.
% This cannot establish realistic failure probabilities or safe holding.
C=struct('centers_m',[0 0 0], ...
  'segmentsA_m',[0 10 0], 'segmentsB_m',[20 10 0], ...
  'segmentRadii_m',1);
assert(abs(FABER_clearance_m([10;14;0],C,1)-2)<1e-9);
mu=398600.4418;Re=6378.1363;h=680.12;
events=struct('xPre',{[0;-400;0;0;0;0]}, ...
    'dvNom',{[0;0.05;0]},'phase',{'Test HCW burn'}, ...
    'vehicle',{'Taxi'},'index',{1});
cfg=struct('N',4,'seed',1,'camForce_N',10, ...
    'vehicleMass_kg',3503.59,'hazards',C, ...
    'screen',struct('passiveHorizon_s',3600,'dt_s',120, ...
       'protectedRadius_m',30,'collisionRadius_m',5, ...
       'burnStep_s',2,'maxExitTime_s',3600));
R=FABER_safety_MC_taxi(events,mu,Re,h,cfg);
assert(height(R.trials)==4);
assert(isfield(R,'summary'));
disp(R.summary);
fprintf('FABER smoke test finished.\n');
end
